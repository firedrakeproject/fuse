"""Tests for the stabiliser and representation of a generator's DOFs."""
import numpy as np
import pytest

from fuse import (Point, PolynomialKernel, DOF, L2Pairing, DOFGenerator, ElementTriple,
                  PolynomialSpace, S1, S2, C0, H1, HCurl)
from fuse.element_construction import periodic_table


def reflection(G):
    return [g for g in G.members() if g.perm.order() == 2][0]


def interval_moment(action):
    """The moment of v against 1 on an interval, as a single generator."""
    interval = Point(1, [Point(0), Point(0)], vertex_num=2)
    xs = [DOF(L2Pairing(), PolynomialKernel(1, action=action))]
    triple = ElementTriple(interval, (PolynomialSpace(0), C0), DOFGenerator(xs, S1))
    return triple


@pytest.mark.parametrize("action,sign", [(H1, 1), (HCurl, -1)])
def test_interval_moment(action, sign):
    """The reflection of an interval keeps the moment of a 0-form and negates
    the moment of a 1-form."""
    triple = interval_moment(action)
    gen = triple.DOFGenerator[0]
    H = gen.stabiliser()
    assert H.size() == 2
    r = reflection(H)
    assert np.allclose(gen.representation()[tuple(r.perm.array_form)], [[sign]])


def test_nd_edge():
    """The lowest order Nedelec element on a triangle: the generator is the
    tangential moment on one edge. It is kept by the reflection fixing that
    edge, which reverses the tangent, and the three rotations are a
    transversal."""
    triple = periodic_table(0, 2, 1, 1)
    gen = triple.DOFGenerator[0]
    H = gen.stabiliser()
    assert H.size() == 2
    assert np.allclose(gen.representation()[tuple(reflection(H).perm.array_form)], [[-1]])
    gen.check_transversal()


@pytest.mark.parametrize("p", [(0, 2, 1, 1), (0, 2, 2, 2), (1, 2, 1, 2), (0, 3, 1, 1), (0, 3, 2, 1)])
def test_representation_is_a_homomorphism(p):
    """rho(h o g) = rho(h) rho(g) on the stabiliser of every generator."""
    triple = periodic_table(*p)
    for gen in triple.DOFGenerator:
        H = gen.stabiliser()
        rho = gen.representation()
        for g in H.members():
            for h in H.members():
                hg = tuple(h.compose(g).perm.array_form)
                assert np.allclose(rho[hg], rho[tuple(h.perm.array_form)] @ rho[tuple(g.perm.array_form)])


def test_constant_interior_vectors():
    """The interior of the degree 2 Nedelec element on a triangle is two
    constant vector moments. Together they span the constant vectors, which
    every symmetry preserves, so they form one generator with a trivial
    transversal."""
    triple = periodic_table(0, 2, 1, 2)
    interior = triple.DOFGenerator[1]
    assert len(interior.generator_dofs()) == 2
    assert interior.stabiliser().size() == 6
    interior.check_transversal()


def test_transversal_must_cover_the_cosets():
    """The tangential moment on one edge of a triangle is kept only by the
    identity and the reflection fixing that edge, so its images lie in three
    cosets: generated by the identity alone it does not reach them."""
    nd = periodic_table(0, 2, 1, 1)
    gen = DOFGenerator(nd.DOFGenerator[0].x, S1)
    ElementTriple(nd.cell, nd.spaces, gen)
    assert gen.stabiliser().size() == 2
    with pytest.raises(ValueError):
        gen.check_transversal()


def test_stabiliser_without_conversion():
    """H_X and rho_X do not depend on whether the triple has been converted
    for FIAT: the space evaluates the DOFs from the cell's geometry."""
    results = []
    for convert in (False, True):
        triple = periodic_table(0, 2, 1, 2)
        if convert:
            triple.to_ufl()
        gen = triple.DOFGenerator[0]
        results.append(({tuple(h.perm.array_form) for h in gen.stabiliser().members()},
                        gen.representation()))
    (H0, rho0), (H1_, rho1) = results
    assert H0 == H1_
    assert all(np.allclose(rho0[k], rho1[k]) for k in rho0)


def test_generator_belongs_to_one_triple():
    interval = Point(1, [Point(0), Point(0)], vertex_num=2)
    gen = DOFGenerator([DOF(L2Pairing(), PolynomialKernel(1))], S1)
    ElementTriple(interval, (PolynomialSpace(0), C0), gen)
    with pytest.raises(ValueError, match="already belongs"):
        ElementTriple(interval, (PolynomialSpace(1), C0), gen)


def test_g2_has_been_removed():
    with pytest.raises(TypeError, match="G2"):
        DOFGenerator([DOF(L2Pairing(), PolynomialKernel(1))], S1, S2)
